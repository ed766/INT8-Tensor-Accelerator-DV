#!/usr/bin/env python3
"""Check the executable AES+INT8 combined-host evidence.

The firmware mailbox is deliberately not used as the oracle.  This checker
requires a complete RVFI-style trace, checks AES words against an independent
Python AES model, and proves that accelerator activity overlapped an active
chiplet interval in the same RTL run.
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CHIPLET_SCRIPTS = Path(os.environ.get("CHIPLET_ROOT", ROOT.parent / "ucie_chiplet_soc")) / "chiplet_extension" / "scripts"
sys.path.insert(0, str(CHIPLET_SCRIPTS))
from dma_golden_model import AES_KEY, encrypt_block  # noqa: E402

from check_crossover_trace import check, events  # noqa: E402


def num(value: str) -> int:
    try:
        return int(value, 0)
    except ValueError:
        return int(value, 16)


def hexnum(value: str) -> int:
    return int(value, 16)


def aes_job_matches(trace_events: list[dict[str,str]]) -> tuple[int,int,str]:
    """Exact block/word accounting for jobs identified by reset epoch and launch.

    A reset may cancel an unfinished block. Already emitted words must still
    equal the prefix independently computed from accepted complete blocks;
    no cancelled word is allowed to migrate to another epoch or launch.
    """
    jobs=[]
    current=None
    observed=0
    for event in trace_events:
        kind=event.get("kind")
        epoch=event.get("epoch","0")
        if kind=="RESET_ASSERT":
            if current is not None:current["aborted"]=True
            current=None
        elif kind=="CHIPLET_EVT":
            busy=num(event.get("busy","0"))!=0
            if busy and (current is None or not current["busy"]):
                current=dict(epoch=epoch,start=event.get("eid",event.get("cycle","")),
                             busy=True,aborted=False,inputs=[],outputs=[])
                jobs.append(current)
            if current is not None:
                if epoch!=current["epoch"]:return observed,0,"AES job state crossed reset epoch"
                current["busy"]=busy
        elif kind in {"CHIPLET_IN","CHIPLET_DIE_B_OUT"}:
            if kind=="CHIPLET_DIE_B_OUT":observed+=1
            if current is None or epoch!=current["epoch"]:
                return observed,0,f"unsolicited {kind} without an owning AES job in epoch {epoch}"
            if kind=="CHIPLET_IN" and not current["busy"]:
                return observed,0,"plaintext accepted outside owning AES execution"
            try:value=hexnum(event["data"])
            except (KeyError,ValueError):return observed,0,"malformed AES job word"
            current["inputs" if kind=="CHIPLET_IN" else "outputs"].append(value)
    matched=0
    for job in jobs:
        words=job["inputs"]
        if len(words)%2 and not job["aborted"]:
            return observed,matched,f"incomplete AES block in epoch {job['epoch']} job {job['start']}"
        expected=[]
        for offset in range(0,len(words)-1,2):expected.extend(encrypt_block(AES_KEY,words[offset:offset+2]))
        actual=job["outputs"]
        required=expected[:len(actual)] if job["aborted"] else expected
        if len(actual)>len(expected) or actual!=required:
            return observed,matched,f"AES job/block/word mismatch in epoch {job['epoch']} job {job['start']}; outputs={len(actual)} expected={len(expected)} aborted={job['aborted']}"
        matched+=len(actual)
    if not jobs:return observed,matched,"no owning AES job observed"
    return observed,matched,""


def aes_matches(trace_events: list[dict[str, str]], intervals: list[tuple[int, int]]) -> tuple[int, int, str]:
    """Return (observed_outputs, matched_outputs, first_failure).

    Accepted plaintext words, including repeated values, are compared with
    every observed AES output in order. No RTL ciphertext is used as a model
    input.
    """
    if any(event.get("kind")=="CHIPLET_EVT" for event in trace_events):
        return aes_job_matches(trace_events)
    plaintext = [0]
    outputs: list[tuple[int, int]] = []
    for event in trace_events:
        kind = event.get("kind")
        try:
            if kind == "CHIPLET_IN":
                word = hexnum(event.get("data", "0"))
                plaintext.append(word)
            elif kind == "CHIPLET_DIE_B_OUT":
                outputs.append((num(event.get("cycle", "0")), hexnum(event.get("data", "0"))))
        except ValueError:
            return 0, 0, f"malformed chiplet stream event at line {event.get('_line')}"
    # Keep compatibility with traces generated by the pre-handshake observer,
    # but prefer explicit accepted-word/output events whenever present.
    if not outputs:
        for event in trace_events:
            if event.get("kind") != "CHIPLET_DATA":
                continue
            try:
                word = hexnum(event.get("plaintext", "0"))
                die_b = hexnum(event.get("die_b_ciphertext", "0"))
            except ValueError:
                return 0, 0, f"malformed CHIPLET_DATA at line {event.get('_line')}"
            if word != plaintext[-1]:
                plaintext.append(word)
            if die_b:
                outputs.append((num(event.get("cycle", "0")), die_b))

    # Attribute the accepted words to the firmware-owned job, not to any
    # pre-launch activity in the optional chiplet integration.
    active_inputs = []
    for event in trace_events:
        if event.get("kind") != "CHIPLET_IN":
            continue
        cycle = num(event.get("cycle", "0"))
        if any(start <= cycle <= end for start, end in intervals):
            active_inputs.append(hexnum(event.get("data", "0")))
    expected_words: list[int] = []
    if not active_inputs:
        return len(outputs), 0, "no accepted plaintext words during the configured chiplet job"
    if len(active_inputs) % 2:
        return len(outputs), 0, f"chiplet accepted an incomplete 128-bit AES block ({len(active_inputs)} words)"
    for index in range(0, len(active_inputs) - 1, 2):
        expected_words.extend(encrypt_block(AES_KEY, active_inputs[index:index + 2]))
    # Output FIFO draining may trail the engine's busy deassertion. Attribute
    # outputs from launch through the next launch (or end of trace) to the job;
    # this catches extra/corrupt tail words without consuming a pre-launch
    # backlog as evidence for the new job.
    interval_windows = [(start, intervals[index + 1][0] if index + 1 < len(intervals) else None)
                        for index, (start, _end) in enumerate(intervals)]
    active_outputs = [value for cycle, value in outputs
                      if any(cycle >= start and (stop is None or cycle < stop)
                             for start, stop in interval_windows)]
    # This is an exact per-job contract, not a subsequence search: missing,
    # reordered, duplicated, and unsolicited output words all fail.
    if active_outputs != expected_words:
        mismatch = next((i for i, (got, want) in enumerate(zip(active_outputs, expected_words))
                         if got != want), min(len(active_outputs), len(expected_words)))
        got = f"{active_outputs[mismatch]:016x}" if mismatch < len(active_outputs) else "<missing>"
        want = f"{expected_words[mismatch]:016x}" if mismatch < len(expected_words) else "<no-word-expected>"
        return len(outputs), sum(a == b for a, b in zip(active_outputs, expected_words)), (
            f"AES output stream mismatch at word {mismatch}: got {got}, expected {want}; "
            f"active outputs={len(active_outputs)} expected={len(expected_words)} "
            f"(extra outputs are rejected)"
        )
    return len(outputs), len(expected_words), ""


def final_aes_destination_words(trace_events: list[dict[str, str]]) -> list[int]:
    """Predict the final reused destination from the last job's plaintext.

    Numerical output ownership is checked separately by aes_job_matches.
    Reset cancels the prior job; ciphertext events are never model inputs.
    """
    plaintext: list[int] = []
    busy = False
    epoch = None
    for event in trace_events:
        if event.get("kind") == "RESET_ASSERT":
            plaintext.clear()
            busy = False
            epoch = None
        elif event.get("kind") == "CHIPLET_EVT":
            next_busy = num(event.get("busy", "0")) != 0
            if next_busy and not busy:
                plaintext.clear()
                epoch = event.get("epoch", "0")
            busy = next_busy
        elif event.get("kind") == "CHIPLET_IN" and busy and event.get("epoch", "0") == epoch:
            plaintext.append(hexnum(event["data"]))
    expected: list[int] = []
    for offset in range(0, len(plaintext) - 1, 2):
        expected.extend(encrypt_block(AES_KEY, plaintext[offset:offset + 2]))
    return expected


def destination_read_error(trace_events: list[dict[str, str]], expected: list[int]) -> str:
    """Compare actual maintenance-port retirement data with expected SRAM words."""
    index = 0
    destination = False
    reading = False
    low: int | None = None
    readbacks: list[tuple[int, int]] = []
    for event in trace_events:
        if event.get("kind") == "RESET_ASSERT":
            index = 0
            destination = False
            reading = False
            low = None
            readbacks.clear()
            continue
        if event.get("kind") == "APB" and event.get("write") == "1":
            addr = event.get("addr")
            if addr == "50000020":
                index = hexnum(event.get("wdata", "0"))
                reading = False
            elif addr == "50000024":
                destination = hexnum(event.get("wdata", "0")) == 1
                reading = False
            elif addr == "50000058":
                reading = destination and hexnum(event.get("wdata", "0")) == 1
                low = None
        elif event.get("kind") == "RETIRE" and reading and event.get("mem_rmask") == "f":
            if event.get("mem_addr") == "50000028":
                if low is not None:
                    return "duplicate destination low-word read without matching high word"
                low = hexnum(event.get("mem_rdata", "0"))
            elif event.get("mem_addr") == "5000002c":
                if low is None:
                    return "destination high-word read has no matching low word"
                readbacks.append((index, (hexnum(event.get("mem_rdata", "0")) << 32) | low))
                low = None
                reading = False
    required = [(32 + offset, word) for offset, word in enumerate(expected)]
    if readbacks != required:
        mismatch = next((i for i, pair in enumerate(zip(readbacks, required)) if pair[0] != pair[1]),
                        min(len(readbacks), len(required)))
        return (f"chiplet destination SRAM readback mismatch at word {mismatch}: "
                f"observed={readbacks[mismatch:mismatch+1]} expected={required[mismatch:mismatch+1]}; "
                f"readbacks={len(readbacks)} required={len(required)}")
    return ""


def return_stream_error(trace_events: list[dict[str, str]], aborted: bool) -> str:
    pending: list[tuple[str, int]] = []
    for event in trace_events:
        kind = event.get("kind")
        if kind == "RESET_ASSERT":
            pending.clear()
        elif kind == "CHIPLET_DIE_B_OUT":
            pending.append((event.get("epoch", "0"), hexnum(event.get("data", "0"))))
        elif kind == "CHIPLET_OUT":
            actual = (event.get("epoch", "0"), hexnum(event.get("data", "0")))
            if aborted or not pending or actual != pending[0]:
                return "chiplet return stream differs from expected ownership/order/epoch"
            pending.pop(0)
    if pending and not aborted:
        return f"chiplet return stream has {len(pending)} unconsumed produced words"
    return ""


def check_host_trace(path: Path, scenario: str | None = None) -> dict[str, object]:
    scenario = scenario or path.parent.name
    parsed = events(path)
    replay = check(path, strict_schema=True)
    errors: list[str] = []
    if replay["status"] != "PASS":
        errors.append("strict crossover replay failed: " + str(replay["errors"]))

    chip_intervals: list[tuple[int, int]] = []
    chip_start: int | None = None
    chip_done = False
    chip_error = False
    expect_parity_error = scenario == "combined_services__case_3"
    accelerator_cycles: list[int] = []
    for event in parsed:
        kind = event.get("kind")
        cycle = num(event.get("cycle", "0"))
        if kind == "CHIPLET_EVT":
            chip_error |= num(event.get("error", "0")) != 0
            busy = num(event.get("busy", "0")) != 0
            done = num(event.get("done", "0")) != 0
            if busy and chip_start is None:
                chip_start = cycle
            if done:
                chip_done = True
            if chip_start is not None and not busy:
                chip_intervals.append((chip_start, cycle))
                chip_start = None
        elif kind in {"ACCEL_CMD", "ACCEL_IN", "ACCEL_OUT"}:
            accelerator_cycles.append(cycle)
    if chip_start is not None:
        chip_intervals.append((chip_start, max((num(e.get("cycle", "0")) for e in parsed), default=chip_start)))
    observed, matched, aes_failure = aes_matches(parsed, chip_intervals)
    if expect_parity_error:
        parity_status = [event for event in parsed if event.get("kind") == "RETIRE" and
                         event.get("mem_addr") == "5000003c" and event.get("mem_rmask") == "f" and
                         (hexnum(event.get("mem_rdata", "0")) & 15) == 6]
        if not chip_error or not parity_status:
            errors.append("expected chiplet parity error and software-visible error code 6 were not both observed")
        if aes_failure:
            errors.append(aes_failure)
        if not chip_intervals:
            errors.append("chiplet parity-fault job did not become active")
    else:
        if observed == 0:
            errors.append("no chiplet ciphertext monitor output was observed")
        if aes_failure:
            errors.append(aes_failure)
        if not chip_done:
            errors.append("chiplet completion was not observed")
        if chip_error:
            errors.append("chiplet error monitor asserted")
    overlap = [cycle for cycle in accelerator_cycles if any(start <= cycle <= end for start, end in chip_intervals)]
    if not overlap and scenario == "combined_k16_b4":
        errors.append("no accelerator event overlapped an active chiplet interval")
    return_failure = return_stream_error(parsed, expect_parity_error)
    if return_failure:
        errors.append(return_failure)
    if expect_parity_error:
        expected_memory = [((0x55550000 + i) << 32) | (0xaaaa0000 + i) for i in range(8)]
    else:
        expected_memory = final_aes_destination_words(parsed)
    destination_failure = destination_read_error(parsed, expected_memory)
    if destination_failure:
        errors.append(destination_failure)
    return {
        "scenario": scenario,
        "status": "PASS" if not errors else "FAIL",
        "trace": str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path),
        "rvfi_retirements": replay.get("retirements", 0),
        "aes_outputs": observed,
        "aes_matches": matched,
        "chiplet_intervals": len(chip_intervals),
        "accelerator_events": len(accelerator_cycles),
        "overlap_events": len(overlap),
        "first_failure": "; ".join(errors) or "none",
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("traces", nargs="*", type=Path)
    parser.add_argument("--from-summary", action="store_true",
                        help="check the canonical combined K4/B1 and K16/B4 runs in compute_host_summary.csv")
    parser.add_argument("--report", type=Path, default=ROOT / "reports/compute_host_evidence.csv")
    args = parser.parse_args()
    inputs: list[tuple[Path, str]] = [(path, path.parent.name) for path in args.traces]
    if args.from_summary:
        wanted = {"combined_k4_b1", "combined_k16_b4"}
        with (ROOT / "reports/compute_host_summary.csv").open(newline="") as handle:
            summary = list(csv.DictReader(handle))
        selected = [row for row in summary if row.get("scenario") in wanted and row.get("status") == "PASS"]
        if {row.get("scenario") for row in selected} != wanted:
            raise SystemExit("combined-host summary is missing a passing K4/B1 or K16/B4 run")
        inputs = [(ROOT / row["trace"], row["scenario"]) for row in selected]
    if not inputs:
        parser.error("provide trace paths or --from-summary")
    rows = [check_host_trace(path, scenario) for path, scenario in inputs]
    if args.from_summary and {row["scenario"] for row in rows} != {"combined_k4_b1", "combined_k16_b4"}:
        raise SystemExit("combined-host evidence did not cover both required scenarios")
    if not any(int(row["overlap_events"]) > 0 for row in rows):
        rows[0]["status"] = "FAIL"
        rows[0]["first_failure"] = (str(rows[0]["first_failure"]) + "; " if rows[0]["first_failure"] != "none" else "") + "combined suite has no measured AES/INT8 overlap"
    args.report.parent.mkdir(parents=True, exist_ok=True)
    with args.report.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    passed = sum(row["status"] == "PASS" for row in rows)
    print(f"COMPUTE_HOST_EVIDENCE|status={'PASS' if passed == len(rows) else 'FAIL'}|rows={passed}/{len(rows)}")
    return 0 if passed == len(rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
